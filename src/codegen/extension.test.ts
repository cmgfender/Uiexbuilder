import { describe, expect, it } from 'vitest';
import { createExtension, createProject } from '../model/factory';
import type {
  ActionStep,
  CardLocation,
  DataSource,
  ExtensionKind,
  NodeTemplate,
  Project,
  StateVar,
} from '../model/types';
import { generateExtensionSource } from './index';

interface Options {
  kind?: ExtensionKind;
  location?: CardLocation;
  state?: StateVar[];
  dataSources?: DataSource[];
  setup?: (project: Project) => void;
}

/** Generates the source of a single extension built from `content`. */
function gen(content: NodeTemplate[], opts: Options = {}): string {
  const project = createProject('Test App', []);
  const ext = createExtension({ kind: opts.kind ?? 'card', location: opts.location, name: 'Test', content });
  ext.state = opts.state ?? [];
  ext.dataSources = opts.dataSources ?? [];
  project.extensions = [ext];
  opts.setup?.(project);
  return generateExtensionSource(project, ext);
}

let n = 0;
const step = (s: Record<string, unknown>): ActionStep => ({ id: `a_${++n}`, ...s }) as unknown as ActionStep;
const st = (name: string, type: StateVar['type'], initial: StateVar['initial']): StateVar => ({ id: `s_${name}`, name, type, initial });

/** The JSX returned by the component (between `return (` and `);`). */
function jsxOf(source: string): string {
  const start = source.indexOf('  return (\n');
  if (start === -1) return source.slice(source.indexOf('return '));
  return source.slice(start, source.indexOf('\n  );\n', start));
}

describe('extension skeleton', () => {
  it('follows the HubSpot template entry point for cards', () => {
    const src = gen([{ type: 'Text', text: 'Hi' }]);
    expect(src).toContain("// Test — app card (crm.record.tab).\n// Generated by UI Extension Builder.");
    expect(src).toContain("import { hubspot, Text } from '@hubspot/ui-extensions';");
    expect(src).toContain("import type {\n  CrmContext,\n  ExtensionPointApiActions,\n} from '@hubspot/ui-extensions';");
    expect(src).toContain(
      "interface ExtensionProps {\n  context: CrmContext;\n  actions: ExtensionPointApiActions<'crm.record.tab'>;\n}",
    );
    expect(src).toContain(
      "hubspot.extend<'crm.record.tab'>(({ context, actions }: ExtensionProps) => (\n  <TestCard context={context} actions={actions} />\n));",
    );
    expect(src).toContain('const TestCard = (_props: ExtensionProps) => {');
    expect(src).not.toContain('react');
    expect(src).not.toContain('eslint-disable');
  });

  it('uses the location of the card and the right context type per kind', () => {
    expect(gen([], { location: 'crm.record.sidebar' })).toContain("hubspot.extend<'crm.record.sidebar'>");
    const settings = gen([], { kind: 'settings' });
    expect(settings).toContain('context: SettingsContext;');
    expect(settings).toContain("actions: ExtensionPointApiActions<'settings'>;");
    const home = gen([], { kind: 'home' });
    expect(home).toContain('context: AppHomeContext;');
    expect(home).toContain("hubspot.extend<'home'>");
  });

  it('renders an empty root as an empty fragment', () => {
    expect(gen([])).toContain('  return <></>;\n};');
  });

  it('destructures only the props that are used', () => {
    expect(gen([{ type: 'Text', text: '{{ context.user.firstName }}' }])).toContain('const TestCard = ({ context }: ExtensionProps)');
    const withAction = gen([{ type: 'Button', text: 'Go', events: { onClick: [step({ type: 'reloadPage' })] } }]);
    expect(withAction).toContain('const TestCard = ({ actions }: ExtensionProps)');
  });

  it('is deterministic and independent of node ids', () => {
    const content: NodeTemplate[] = [
      { type: 'Flex', children: [{ type: 'Button', text: 'A', events: { onClick: [step({ type: 'log', level: 'info', message: 'x' })] } }] },
    ];
    expect(gen(content)).toBe(gen(content));
  });
});

describe('templates and text', () => {
  it('prints plain, single-segment and mixed text children', () => {
    const src = gen([
      { type: 'Text', text: 'Plain text' },
      { type: 'Text', text: '{{ count }}' },
      { type: 'Text', text: 'Count: {{ count }}!' },
      { type: 'Text', text: '' },
    ], { state: [st('count', 'number', 0)] });
    const jsx = jsxOf(src);
    expect(jsx).toContain('<Text>Plain text</Text>');
    expect(jsx).toContain('<Text>{toText(count)}</Text>');
    expect(jsx).toContain('<Text>Count: {toText(count)}!</Text>');
    expect(jsx).toContain("<Text>{''}</Text>");
  });

  it('escapes JSX-special characters and preserves whitespace', () => {
    const jsx = jsxOf(gen([
      { type: 'Text', text: 'a {b} <c> & d' },
      { type: 'Text', text: '  padded ' },
      { type: 'Text', text: 'two\nlines' },
      { type: 'Text', text: ' {{ x }} & `y`' },
    ], { state: [st('x', 'string', '')] }));
    expect(jsx).toContain("<Text>{'a {b} <c> & d'}</Text>");
    expect(jsx).toContain("<Text>{'  padded '}</Text>");
    expect(jsx).toContain("<Text>{'two\\nlines'}</Text>");
    expect(jsx).toContain('<Text>{` ${toText(x)} & \\`y\\``}</Text>');
  });

  it('emits the toText helper once, only when needed', () => {
    expect(gen([{ type: 'Text', text: 'static' }])).not.toContain('const toText');
    const src = gen([
      { type: 'Text', text: '{{ a }}' },
      { type: 'Heading', text: 'b {{ a }}' },
    ], { state: [st('a', 'string', '')] });
    expect(src.match(/const toText = /g)).toHaveLength(1);
    expect(src).toContain('const toText = (value: unknown): string =>');
  });

  it('applies template rules to props', () => {
    const jsx = jsxOf(gen([
      {
        type: 'ProgressBar',
        props: {
          title: 'Done: {{ count }}%',
          value: '{{ count }}',
          valueDescription: 'plain "quoted"',
          'aria-label': '{{ }}',
        },
      },
    ], { state: [st('count', 'number', 0)] }));
    expect(jsx).toContain('title={`Done: ${toText(count)}%`}');
    expect(jsx).toContain('value={count}');
    expect(jsx).toContain("valueDescription={'plain \"quoted\"'}");
    expect(jsx).toContain('aria-label=""');
  });
});

