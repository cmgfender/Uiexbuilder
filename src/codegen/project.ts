/** File-system safe base name (letters, digits, `_`, `-`). */
function safeFileBase(name: string, fallback: string): string {
  const cleaned = name.trim().replace(/[^A-Za-z0-9_-]+/g, '-').replace(/^-+|-+$/g, '');
  return cleaned || fallback;
}

function uniqueIn(base: string, taken: Set<string>): string {
  let name = base;
  let i = 2;
  while (taken.has(name.toLowerCase())) name = `${base}${i++}`;
  taken.add(name.toLowerCase());
  return name;
}

/** Where an extension and its config live in the generated project. */
export interface ExtensionFiles {
  ext: Extension;
  dir: string;
  /** e.g. "src/app/cards/ContactCard.tsx" */
  sourcePath: string;
  /** e.g. "/app/cards/ContactCard.tsx" (hsmeta entrypoint, relative to srcDir) */
  entrypoint: string;
  metaPath: string;
}

/** Deterministic file layout of every extension (unique names per directory). */
export function planExtensionFiles(project: Project): ExtensionFiles[] {
  const takenByDir = new Map<string, Set<string>>();
  let settingsMetaUsed = false;
  return project.extensions.map((ext) => {
    const dirName = UI_DIRS[ext.kind];
    const dir = `src/app/${dirName}`;
    if (!takenByDir.has(dir)) takenByDir.set(dir, new Set());
    const taken = takenByDir.get(dir)!;
    const base = uniqueIn(/^[A-Za-z0-9_-]+$/.test(ext.fileName) ? ext.fileName : componentName(ext), taken);
    let metaBase: string;
    if (ext.kind === 'card') metaBase = `${base}-hsmeta.json`;
    else if (ext.kind === 'settings' && !settingsMetaUsed) {
      settingsMetaUsed = true;
      metaBase = 'settings-hsmeta.json';
    } else metaBase = `${safeFileBase(ext.uid, base)}-hsmeta.json`;
    if (taken.has(metaBase.toLowerCase())) metaBase = `${base}-hsmeta.json`;
    taken.add(metaBase.toLowerCase());
    return {
      ext,
      dir,
      sourcePath: `${dir}/${base}.tsx`,
      entrypoint: `/app/${dirName}/${base}.tsx`,
      metaPath: `${dir}/${metaBase}`,
    };
  });
}

interface FunctionFiles {
  fn: AppFunction;
  sourcePath: string;
  entrypoint: string;
  metaPath: string;
}

function planFunctionFiles(project: Project): FunctionFiles[] {
  const taken = new Set<string>(['package']);
  return project.functions.map((fn) => {
    const base = uniqueIn(safeFileBase(fn.fileName, toPascalCase(fn.uid, 'Function')), taken);
    return {
      fn,
      sourcePath: `src/app/functions/${base}.js`,
      entrypoint: `/app/functions/${base}.js`,
      metaPath: `src/app/functions/${base}-hsmeta.json`,
    };
  });
}

function extensionMeta(files: ExtensionFiles): unknown {
  const { ext } = files;
  if (ext.kind === 'settings') {
    return { uid: ext.uid, type: 'settings', config: { entrypoint: files.entrypoint } };
  }
  if (ext.kind === 'home') {
    return { uid: ext.uid, type: 'page', config: { entrypoint: files.entrypoint, location: 'home' } };
  }
  const config: Record<string, unknown> = { name: ext.name };
  if (ext.description && ext.description.trim()) config.description = ext.description.trim();
  config.location = ext.location;
  config.entrypoint = files.entrypoint;
  config.objectTypes = Array.isArray(ext.objectTypes) ? ext.objectTypes : [];
  return { uid: ext.uid, type: 'card', config };
}

function appMeta(project: Project, req: ProjectRequirements): unknown {
  const app = project.app;
  const auth: Record<string, unknown> = { type: app.authType };
  if (app.authType === 'oauth') auth.redirectUrls = app.redirectUrls;
  auth.requiredScopes = mergeRequiredScopes(app, req.scopes);
  auth.optionalScopes = app.optionalScopes;
  auth.conditionallyRequiredScopes = app.conditionallyRequiredScopes;
  const support: Record<string, string> = {};
  for (const [key, value] of Object.entries(app.support)) if (value && value.trim()) support[key] = value.trim();
  const config: Record<string, unknown> = {
    description: app.description,
    name: app.name,
    distribution: app.distribution,
    auth,
    permittedUrls: {
      fetch: mergeUrls(app.permittedUrls.fetch, req.fetch),
      iframe: mergeUrls(app.permittedUrls.iframe, req.iframe),
      img: mergeUrls(app.permittedUrls.img, req.img),
    },
  };
  if (Object.keys(support).length) config.support = support;
  return { uid: app.uid, type: 'app', config };
}

function uiPackageJson(project: Project, dirName: string): string {
  return formatJson({
    name: `${toProjectSlug(project.name)}-${dirName}`,
    version: '0.1.0',
    license: 'MIT',
    type: 'module',
    scripts: TEMPLATE_SCRIPTS,
    dependencies: {
      '@hubspot/ui-extensions': UI_EXTENSIONS_VERSION,
      react: REACT_VERSION,
    },
    devDependencies: TEMPLATE_DEV_DEPENDENCIES,
  });
}

function functionsPackageJson(project: Project): string {
  return formatJson({
    name: `${toProjectSlug(project.name)}-functions`,
    version: '0.1.0',
    dependencies: { '@hubspot/api-client': API_CLIENT_VERSION },
  });
}

const LOCATION_HELP: Record<string, string> = {
  'crm.record.tab': 'a tab in the middle column of the record page',
  'crm.record.sidebar': 'the right sidebar of the record page',
  'crm.preview': 'the record preview panel',
  'helpdesk.sidebar': 'the help desk ticket sidebar',
  settings: "the app's settings page (Settings → Integrations → Connected apps)",
  home: "the app's home page (Marketplace icon → your app)",
};

function readme(project: Project, extFiles: ExtensionFiles[], fnFiles: FunctionFiles[], appJson: unknown): string {
  const app = (appJson as { config: { auth: { requiredScopes: string[] }; permittedUrls: Record<string, string[]> } }).config;
  const lines: string[] = [];
  lines.push(`# ${project.app.name}`);
  lines.push('');
  if (project.app.description.trim()) {
    lines.push(project.app.description.trim());
    lines.push('');
  }
  lines.push(
    `HubSpot developer project (platform version ${project.platformVersion}) generated by UI Extension Builder.`,
  );
  lines.push('');
  lines.push('## Contents');
  lines.push('');
  lines.push('| Extension | Type | Appears in | File |');
  lines.push('| --- | --- | --- | --- |');
  for (const f of extFiles) {
    const location = extensionLocation(f.ext);
    const kind = f.ext.kind === 'card' ? 'App card' : f.ext.kind === 'settings' ? 'Settings page' : 'App home page';
    const where =
      f.ext.kind === 'card'
        ? `${LOCATION_HELP[location] ?? location} of ${(f.ext.objectTypes ?? []).join(', ') || 'CRM'} records`
        : LOCATION_HELP[location];
    lines.push(`| ${escapeCell(f.ext.name)} | ${kind} | ${escapeCell(where)} | \`${f.sourcePath}\` |`);
  }
  if (fnFiles.length) {
    lines.push('');
    lines.push('App functions (called with `hubspot.serverless(uid, ...)`):');
    lines.push('');
    for (const f of fnFiles) lines.push(`- \`${f.fn.uid}\` — \`${f.sourcePath}\``);
  }
  lines.push('');
  lines.push('## Requirements');
  lines.push('');
  lines.push('- A HubSpot account with access to developer projects');
  lines.push('- Node.js 20+ and npm');
  lines.push('- The HubSpot CLI: `npm install -g @hubspot/cli@latest`');
  lines.push('');
  lines.push('## Deploy');
  lines.push('');
  lines.push('```bash');
  lines.push('# 1. Connect the CLI to your HubSpot account (once)');
  lines.push('hs account auth');
  lines.push('');
  lines.push('# 2. Install dependencies');
  const dirs = [...new Set(extFiles.map((f) => f.dir))];
  if (fnFiles.length) dirs.push('src/app/functions');
  for (const dir of dirs) lines.push(`(cd ${dir} && npm install)`);
  lines.push('');
  lines.push('# 3. Upload and deploy the project');
  lines.push('hs project upload');
  lines.push('');
  lines.push('# Optional: run locally with hot reload against your account');
  lines.push('hs project dev');
  lines.push('```');
  lines.push('');
  if (extFiles.some((f) => f.ext.kind === 'card')) {
    lines.push(
      'After the upload, add each card to a record view: open a record, click **Customize**, choose a tab, click **+**, filter the card library by **App** and select the card.',
    );
    lines.push('');
  }
  lines.push('## Scopes and permitted URLs');
  lines.push('');
  lines.push('Configured in `src/app/app-hsmeta.json`:');
  lines.push('');
  lines.push(`- Required scopes: ${listOrNone(app.auth.requiredScopes)}`);
  lines.push(`- Fetch URLs (\`hubspot.fetch\`): ${listOrNone(app.permittedUrls.fetch)}`);
  lines.push(`- Iframe URLs: ${listOrNone(app.permittedUrls.iframe)}`);
  lines.push(`- Image URLs: ${listOrNone(app.permittedUrls.img)}`);
  lines.push('');
  lines.push('## Editing');
  lines.push('');
  lines.push(
    'The code is plain React + TypeScript using `@hubspot/ui-extensions`; edit it directly, or import `.uiex.json` into UI Extension Builder to keep designing visually and export again.',
  );
  lines.push('');
  return lines.join('\n');
}

function listOrNone(values: string[]): string {
  return values.length ? values.map((v) => `\`${v}\``).join(', ') : '_none_';
}

function escapeCell(text: string): string {
  return text.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
}

/** Every file of the HubSpot project, in a stable order. */
export function generateProjectFiles(project: Project): GeneratedFile[] {
  const req = deriveRequirements(project);
  const extFiles = planExtensionFiles(project);
  const fnFiles = planFunctionFiles(project);
  const app = appMeta(project, req);

  const files: GeneratedFile[] = [];
  files.push({
    path: 'hsproject.json',
    contents: formatJson({ name: project.name, srcDir: 'src', platformVersion: project.platformVersion }),
  });
  files.push({ path: 'README.md', contents: readme(project, extFiles, fnFiles, app) });
  files.push({ path: '.gitignore', contents: TEMPLATE_GITIGNORE });
  files.push({ path: '.uiex.json', contents: `${serializeProject(project)}\n` });
  files.push({ path: 'src/app/app-hsmeta.json', contents: formatJson(app) });

  for (const kind of ['card', 'settings', 'home'] as const) {
    const group = extFiles.filter((f) => f.ext.kind === kind);
    if (group.length === 0) continue;
    const dirName = UI_DIRS[kind];
    const dir = `src/app/${dirName}`;
    for (const f of group) {
      files.push({ path: f.sourcePath, contents: generateExtensionSource(project, f.ext) });
      files.push({ path: f.metaPath, contents: formatJson(extensionMeta(f)) });
    }
    files.push({ path: `${dir}/package.json`, contents: uiPackageJson(project, dirName) });
    files.push({ path: `${dir}/tsconfig.json`, contents: formatJson(TEMPLATE_TSCONFIG) });
    files.push({ path: `${dir}/.prettierrc.json`, contents: TEMPLATE_PRETTIERRC });
    files.push({ path: `${dir}/eslint.config.js`, contents: TEMPLATE_ESLINT_CONFIG });
  }

  if (fnFiles.length) {
    for (const f of fnFiles) {
      const source = typeof f.fn.code === 'string' ? f.fn.code : '';
      files.push({ path: f.sourcePath, contents: source.endsWith('\n') ? source : `${source}\n` });
      const config: Record<string, unknown> = { entrypoint: f.entrypoint };
      const endpointPath = typeof f.fn.endpoint?.path === 'string' ? f.fn.endpoint.path.trim() : '';
      if (f.fn.endpoint && endpointPath) {
        config.endpoint = { path: endpointPath, methods: Array.isArray(f.fn.endpoint.methods) ? f.fn.endpoint.methods : ['GET'] };
      }
      config.secretKeys = Array.isArray(f.fn.secretKeys) ? f.fn.secretKeys : [];
      files.push({ path: f.metaPath, contents: formatJson({ uid: f.fn.uid, type: 'app-function', config }) });
    }
    files.push({ path: 'src/app/functions/package.json', contents: functionsPackageJson(project) });
  }
  return files;
}
