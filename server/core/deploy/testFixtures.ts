/**
 * Test fixture: the files generateProjectFiles (src/codegen/project.ts) writes for a project with
 * an app card, a settings page, an app home page and an app function (same layout and hsmeta
 * contents; component sources shortened). Server tests use it instead of importing the browser
 * code generator.
 */
import type { DeployFile } from './paths';

const UI_PACKAGE = (name: string, dir: string) =>
  `${JSON.stringify(
    {
      name: `${name}-${dir}`,
      version: '0.1.0',
      license: 'MIT',
      type: 'module',
      dependencies: { '@hubspot/ui-extensions': '^0.17.1', react: '^18.2.0' },
      devDependencies: { typescript: '^5' },
    },
    null,
    2,
  )}\n`;

export interface SampleProjectOptions {
  name?: string;
  platformVersion?: string;
  functions?: boolean;
  /** App distribution / auth (default private + static). */
  distribution?: 'private' | 'marketplace';
  authType?: 'static' | 'oauth';
}

export function sampleProjectFiles(opts: SampleProjectOptions = {}): DeployFile[] {
  const name = opts.name ?? 'deal-desk';
  const platformVersion = opts.platformVersion ?? '2026.03';
  const app = {
    uid: 'deal_desk',
    type: 'app',
    config: {
      description: 'Built with UI Extension Builder.',
      name: 'Deal Desk',
      distribution: opts.distribution ?? 'private',
      auth: { type: opts.authType ?? 'static', requiredScopes: ['oauth', 'crm.objects.deals.read'], optionalScopes: [], conditionallyRequiredScopes: [] },
      permittedUrls: { fetch: [], iframe: [], img: [] },
      support: { supportEmail: 'support@example.com' },
    },
  };
  const files: DeployFile[] = [
    { path: 'hsproject.json', contents: `${JSON.stringify({ name, srcDir: 'src', platformVersion }, null, 2)}\n` },
    { path: 'README.md', contents: '# Deal Desk\n\nHubSpot developer project generated by UI Extension Builder.\n' },
    { path: '.gitignore', contents: 'node_modules\n' },
    { path: '.uiex.json', contents: '{"format":"uiex-builder"}\n' },
    { path: 'src/app/app-hsmeta.json', contents: `${JSON.stringify(app, null, 2)}\n` },
    {
      path: 'src/app/cards/DealCard.tsx',
      contents: "import { Text, hubspot } from '@hubspot/ui-extensions';\n\nhubspot.extend(() => <Extension />);\n\nconst Extension = () => <Text>Héllo ✓ deals</Text>;\n",
    },
    {
      path: 'src/app/cards/DealCard-hsmeta.json',
      contents: `${JSON.stringify({ uid: 'deal_card_card', type: 'card', config: { name: 'Deal Card', location: 'crm.record.tab', entrypoint: '/app/cards/DealCard.tsx', objectTypes: ['deals'] } }, null, 2)}\n`,
    },
    { path: 'src/app/cards/package.json', contents: UI_PACKAGE(name, 'cards') },
    { path: 'src/app/cards/tsconfig.json', contents: '{ "compilerOptions": { "jsx": "react-jsx" } }\n' },
    { path: 'src/app/cards/.prettierrc.json', contents: '{ "singleQuote": true }\n' },
    { path: 'src/app/cards/eslint.config.js', contents: 'export default [];\n' },
    { path: 'src/app/settings/Settings.tsx', contents: "import { Text, hubspot } from '@hubspot/ui-extensions';\nhubspot.extend(() => <Text>Settings</Text>);\n" },
    { path: 'src/app/settings/settings-hsmeta.json', contents: `${JSON.stringify({ uid: 'settings', type: 'settings', config: { entrypoint: '/app/settings/Settings.tsx' } }, null, 2)}\n` },
    { path: 'src/app/settings/package.json', contents: UI_PACKAGE(name, 'settings') },
    { path: 'src/app/pages/AppHome.tsx', contents: "import { Text, hubspot } from '@hubspot/ui-extensions';\nhubspot.extend(() => <Text>Home</Text>);\n" },
    { path: 'src/app/pages/app_home-hsmeta.json', contents: `${JSON.stringify({ uid: 'app_home', type: 'page', config: { entrypoint: '/app/pages/AppHome.tsx', location: 'home' } }, null, 2)}\n` },
    { path: 'src/app/pages/package.json', contents: UI_PACKAGE(name, 'pages') },
  ];
  if (opts.functions !== false) {
    files.push(
      { path: 'src/app/functions/get-weather.js', contents: 'exports.main = async () => ({ ok: true });\n' },
      {
        path: 'src/app/functions/get-weather-hsmeta.json',
        contents: `${JSON.stringify({ uid: 'get_weather', type: 'app-function', config: { entrypoint: '/app/functions/get-weather.js', endpoint: { path: '/weather', methods: ['GET'] }, secretKeys: [] } }, null, 2)}\n`,
      },
      { path: 'src/app/functions/package.json', contents: `${JSON.stringify({ name: `${name}-functions`, version: '0.1.0', dependencies: {} }, null, 2)}\n` },
    );
  }
  return files;
}
